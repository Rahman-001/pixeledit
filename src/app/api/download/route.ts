import { NextRequest, NextResponse } from 'next/server';
import JSZip from 'jszip';

export async function POST(req: NextRequest) {
  try {
    const { urls, captions, filename = 'visualcraft_export' } = await req.json();

    if (!urls || typeof urls !== 'object') {
      return NextResponse.json({ error: 'urls object is required' }, { status: 400 });
    }

    const zip = new JSZip();
    const imgFolder = zip.folder('images')!;
    const errors: string[] = [];

    // Fetch all platform images server-side (avoids CORS issues)
    const fetchPromises = Object.entries(urls).map(async ([platform, url]) => {
      try {
        const response = await fetch(url as string);
        if (!response.ok) {
          errors.push(`Failed to fetch ${platform}: ${response.statusText}`);
          return;
        }
        const buffer = await response.arrayBuffer();
        const ext = platform === 'flipkart' || platform === 'amazon' ? 'jpg' : 'webp';
        imgFolder.file(`${platform}.${ext}`, buffer);
      } catch (err) {
        errors.push(`Error fetching ${platform}: ${String(err)}`);
      }
    });

    await Promise.all(fetchPromises);

    // Add captions text file if provided
    if (captions) {
      let captionText = '# VisualCraft — AI Generated Captions\n\n';
      for (const [platform, variants] of Object.entries(captions)) {
        captionText += `## ${platform.toUpperCase()}\n\n`;
        if (Array.isArray(variants)) {
          variants.forEach((cap, i) => {
            captionText += `${i + 1}. ${cap}\n`;
          });
        }
        captionText += '\n';
      }
      captionText += '---\nGenerated by VisualCraft | HackIndia × Cloudinary 2026\n';
      zip.file('captions.txt', captionText);
    }

    // Add README
    zip.file(
      'README.txt',
      `VisualCraft Export — ${new Date().toLocaleDateString('en-IN')}\n\nImages exported:\n${Object.keys(urls)
        .map((p) => `- ${p}`)
        .join('\n')}\n\nPowered by Cloudinary AI\nBuilt for HackIndia × Cloudinary 2026`
    );

    const zipBuffer = await zip.generateAsync({
      type: 'arraybuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    });

    return new NextResponse(zipBuffer, {
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': `attachment; filename="${filename}.zip"`,
        'Content-Length': String(zipBuffer.byteLength),
      },
    });
  } catch (error) {
    console.error('Download API error:', error);
    return NextResponse.json({ error: 'Failed to create ZIP download' }, { status: 500 });
  }
}
